export const languageModes: { value: LanguageMode; label: string }[] = [
  { value: "th", label: "ไทย" },
  { value: "en", label: "English" },
  { value: "bilingual", label: "Bilingual" },
];
export const requiredKeys = Object.keys(en) as (keyof typeof en)[];
export function translate(
  key: keyof typeof en,
  mode: LanguageMode = "en",
): string {
  const english = en[key];
  if (mode === "en") return english;
  if (mode === "th") return th[key];
  return `${english} / ${th[key]}`;
}
export function hasTranslation(key: string): key is keyof typeof en {
  return key in en;
}
export function validateTranslations(): boolean {
  return requiredKeys.every(
    (key) =>
      en[key].trim() &&
      th[key]?.trim() &&
      !/TODO|Translation|คำแปล$/.test(th[key]),
  );
}
